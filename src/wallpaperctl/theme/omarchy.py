def ensure_theme_skeleton(
    theme_dir: Path | None = None,
    *,
    accent_strategy: str = "warmest",
) -> bool:
    """Create the dynamic theme skeleton if it does not exist yet (setup path)."""
    theme_dir = theme_dir or user_theme_dir()
    colors_file = theme_dir / "colors.toml"
    if colors_file.is_file():
        return False

    colors = load_colors_json()
    if not colors:
        wal_colors = home() / ".cache" / "wal" / "colors"
        if wal_colors.is_file():
            lines = [
                line.strip()
                for line in wal_colors.read_text(encoding="utf-8", errors="replace").splitlines()
                if line.strip()
            ]
            if len(lines) >= 16:
                colors = {
                    "special": {
                        "background": lines[0],
                        "foreground": lines[7],
                        "cursor": lines[15],
                    },
                    "colors": {f"color{i}": lines[i] for i in range(16)},
                }
    if not colors:
        colors = fallback_palette()

    write_colors_toml(theme_dir, build_colors_mapping(colors, accent_strategy=accent_strategy))
    (theme_dir / "backgrounds").mkdir(parents=True, exist_ok=True)

    current = home() / ".wallpaper"
    seeded = False
    try:
        if current.is_file():
            wallpaper = Path(current.read_text(encoding="utf-8").strip())
            if wallpaper.is_file():
                sync_theme_media(theme_dir, wallpaper)
                seeded = True
    except OSError as e:
        log.debug("omarchy theme: could not seed backgrounds: %s", e)

    # The omarchy theme switcher only lists themes that ship a preview image.
    if not seeded and not (theme_dir / "preview.png").is_file():
        mapping = build_colors_mapping(colors, accent_strategy=accent_strategy)
        write_palette_preview(theme_dir, mapping)
    return True
